def heart(n=16):
    pts=[]
    for i in range(n+1):
        th=i/n*2*math.pi; st=math.sin(th)
        u=16*st**3/17; v=-(13*math.cos(th)-5*math.cos(2*th)-2*math.cos(3*th)-math.cos(4*th))/17
        pts.append((0.5+u*0.42, 0.52+v*0.42))
    return [pts]

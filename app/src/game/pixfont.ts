/** Tiles of a word: list of [col, row] with the word's top-left at (0, 0); letters 5 wide + 1 gap. */
export function wordTiles(word: string, gap = 1): { tiles: [number, number][]; w: number; h: number } {
  const tiles: [number, number][] = [];
  let x = 0;
  for (const ch of word.toUpperCase()) {
    const g = PIX[ch] ?? PIX[' ']!;
    g.forEach((row, r) => { for (let c = 0; c < row.length; c++) if (row[c] === '#') tiles.push([x + c, r]); });
    x += (ch === ' ' ? 3 : 5) + gap;
  }
  return { tiles, w: x - gap, h: 7 };
}

